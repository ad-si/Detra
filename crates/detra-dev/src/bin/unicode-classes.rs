//! Generate `crates/detra/src/unicode_classes.rs`, the character classes of the
//! byte-level BPE tokenizer, from the Unicode Character Database.
//!
//! Usage: unicode-classes <UnicodeData.txt> <PropList.txt> > crates/detra/src/unicode_classes.rs
//! (`make unicode-classes` downloads the files of the pinned Unicode version.)
//!
//! The table is part of every converted Qwen3.5 model, so changing it (for example by
//! generating it from another Unicode version) changes the model hashes.

use std::fmt::Write as _;
use std::process::ExitCode;

const LETTER: u8 = 1;
const MARK: u8 = 2;
const NUMBER: u8 = 3;
const SPACE: u8 = 4;
const CODE_POINTS: usize = 0x11_0000;

fn code_point(text: &str) -> Result<usize, String> {
    usize::from_str_radix(text.trim(), 16)
        .ok()
        .filter(|&cp| cp < CODE_POINTS)
        .ok_or_else(|| format!("invalid code point {text:?}"))
}

/// Class of every code point from its general category: letter, mark, number or none.
fn categories(unicode_data: &str) -> Result<Vec<u8>, String> {
    let mut classes = vec![0u8; CODE_POINTS];
    let mut range_start = None;
    for line in unicode_data.lines().filter(|l| !l.is_empty()) {
        let fields: Vec<&str> = line.split(';').collect();
        let [cp, name, category, ..] = fields[..] else { return Err(format!("invalid line {line:?}")) };
        let cp = code_point(cp)?;
        let class = match category.as_bytes().first() {
            Some(b'L') => LETTER,
            Some(b'M') => MARK,
            Some(b'N') => NUMBER,
            _ => 0,
        };
        // Large blocks are given as a pair of `<Name, First>` and `<Name, Last>` lines.
        let first = if name.ends_with(", Last>") {
            range_start.take().ok_or_else(|| format!("range end without start: {line:?}"))?
        } else {
            cp
        };
        if name.ends_with(", First>") {
            range_start = Some(cp);
            continue;
        }
        classes[first..=cp].fill(class);
    }
    Ok(classes)
}

/// Code points with the White_Space property.
fn white_space(prop_list: &str) -> Result<Vec<(usize, usize)>, String> {
    let mut ranges = Vec::new();
    for line in prop_list.lines() {
        let data = line.split('#').next().unwrap_or("");
        let Some((points, property)) = data.split_once(';') else { continue };
        if property.trim() != "White_Space" {
            continue;
        }
        let (first, last) = points.split_once("..").unwrap_or((points, points));
        ranges.push((code_point(first)?, code_point(last)?));
    }
    Ok(ranges)
}

fn generate(unicode_data: &str, prop_list: &str) -> Result<String, String> {
    let version = prop_list
        .lines()
        .next()
        .and_then(|l| l.strip_prefix("# PropList-"))
        .and_then(|l| l.strip_suffix(".txt"))
        .ok_or("PropList.txt does not start with its version")?;
    let mut classes = categories(unicode_data)?;
    for (first, last) in white_space(prop_list)? {
        classes[first..=last].fill(SPACE);
    }
    let mut ranges: Vec<[usize; 3]> = Vec::new();
    for (cp, &class) in classes.iter().enumerate().filter(|(_, &c)| c != 0) {
        match ranges.last_mut() {
            Some(r) if r[2] == class as usize && r[1] + 1 == cp => r[1] = cp,
            _ => ranges.push([cp, cp, class as usize]),
        }
    }
    let mut out = String::new();
    let _ = writeln!(out, "//! Generated by `make unicode-classes` from Unicode {version}. Do not edit.");
    let _ = writeln!(out, "//!");
    let _ = writeln!(out, "//! Character classes of the byte-level BPE tokenizer as `[first, last, class]` ranges,");
    let _ = writeln!(out, "//! sorted and disjoint: 1 = letter (L), 2 = mark (M), 3 = number (N), 4 = White_Space.");
    let _ = writeln!(out);
    let _ = writeln!(out, "pub const UNICODE_VERSION: &str = \"{version}\";");
    let _ = writeln!(out);
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub const CLASSES: [[u32; 3]; {}] = [", ranges.len());
    for row in ranges.chunks(4) {
        let row: Vec<String> = row.iter().map(|[a, b, c]| format!("[0x{a:X}, 0x{b:X}, {c}],")).collect();
        let _ = writeln!(out, "    {}", row.join(" "));
    }
    let _ = writeln!(out, "];");
    Ok(out)
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [unicode_data, prop_list] = &args[..] else {
        eprintln!("usage: unicode-classes <UnicodeData.txt> <PropList.txt>");
        return ExitCode::FAILURE;
    };
    let read = |path: &String| std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"));
    match read(unicode_data).and_then(|u| generate(&u, &read(prop_list)?)) {
        Ok(out) => {
            print!("{out}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::generate;

    #[test]
    fn builds_merged_ranges() {
        let data = "0030;DIGIT ZERO;Nd;;;\n0031;DIGIT ONE;Nd;;;\n0041;LATIN CAPITAL LETTER A;Lu;;;\n\
                    0300;COMBINING GRAVE ACCENT;Mn;;;\n4E00;<CJK Ideograph, First>;Lo;;;\n\
                    9FFF;<CJK Ideograph, Last>;Lo;;;\n";
        let props = "# PropList-1.2.3.txt\n0009..000D    ; White_Space # Cc\n0020 ; White_Space\n0030 ; Other\n";
        let out = generate(data, props).unwrap();
        assert!(out.contains("UNICODE_VERSION: &str = \"1.2.3\""));
        let table = "[[u32; 3]; 6] = [\n    [0x9, 0xD, 4], [0x20, 0x20, 4], [0x30, 0x31, 3], [0x41, 0x41, 1],\n    \
                     [0x300, 0x300, 2], [0x4E00, 0x9FFF, 1],\n];\n";
        assert!(out.ends_with(table), "{out}");
    }
}
